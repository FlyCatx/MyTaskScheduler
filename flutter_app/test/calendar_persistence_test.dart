// Calendar persistence and version inheritance (0.06).
//
// Requirements covered here:
//   * a version written by 0.06 keeps its segments, availability rules, occupancy and
//     timezone through a save/load cycle (i.e. after a restart);
//   * a version written before 0.06 (no `calendar` key) still loads, and is never read
//     as "24/7 available";
//   * the per-conversation gantt sub-mode survives a restart;
//   * version inheritance keeps arrangements of tasks that still exist and drops the
//     ones whose task was removed.

import 'package:flutter_test/flutter_test.dart';
import 'package:taskscheduler_flutter/src/model/calendar.dart';
import 'package:taskscheduler_flutter/src/model/plan.dart';
import 'package:taskscheduler_flutter/src/model/session.dart';
import 'package:taskscheduler_flutter/src/state/session_store.dart';

import 'support/test_support.dart';

const int _offset = 480;

DateTime at(String wall) {
  final parts = wall.split(' ');
  final date = parts[0].split('-').map(int.parse).toList();
  final time =
      parts.length > 1 ? parts[1].split(':').map(int.parse).toList() : [0, 0];
  return DateTime.utc(date[0], date[1], date[2], time[0], time[1])
      .subtract(const Duration(minutes: _offset));
}

CalendarSchedule sampleCalendar() => CalendarSchedule(
      settings: const CalendarSettings(
        timezoneOffsetMinutes: _offset,
        planningStartDate: '2026-11-18',
        planningDays: 14,
        weekly: WeeklyAvailability({
          1: [WallClockRange(480, 720), WallClockRange(840, 1440)],
          3: [WallClockRange(480, 1440)],
        }),
        exceptions: [
          CalendarDateException(
            date: '2026-11-21',
            closed: true,
            note: '看巡演',
          ),
        ],
        occupancies: [
          CalendarOccupancy(
            id: 'occ-1',
            title: '线性代数',
            kind: 'course',
            weekday: 3,
            ranges: [WallClockRange(540, 620)],
          ),
        ],
        pendingNotes: ['午休半小时，未给出具体时间'],
      ),
      segments: [
        ScheduleSegment(
          id: 'seg-1',
          taskId: 'task-a',
          start: at('2026-11-18 08:00'),
          end: at('2026-11-18 09:30'),
          source: SegmentSource.manual,
        ),
        ScheduleSegment(
          id: 'seg-2',
          taskId: 'task-b',
          start: at('2026-11-19 14:00'),
          end: at('2026-11-19 15:00'),
          source: SegmentSource.auto,
          tentative: true,
        ),
      ],
      autoGenerated: true,
      note: '自动安排完成',
    );

PlanVersion versionWith(CalendarSchedule calendar, {List<TaskRecord>? tasks}) =>
    PlanVersion(
      id: 'ver-1',
      conversationId: 'conv-1',
      createdAt: DateTime.utc(2026, 11, 18),
      summary: '排程',
      tasks: tasks ??
          const [
            TaskRecord(id: 'task-a', name: 'A', estimatedHours: 1.5),
            TaskRecord(id: 'task-b', name: 'B', estimatedHours: 1),
          ],
      calendar: calendar,
    );

void main() {
  test('calendar data survives a JSON round-trip', () {
    final original = sampleCalendar();
    final decoded = PlanVersion.fromJson(versionWith(original).toJson());
    final calendar = decoded.calendar;

    expect(calendar.autoGenerated, isTrue);
    expect(calendar.note, '自动安排完成');
    expect(calendar.segments.length, 2);
    expect(calendar.segments.first.id, 'seg-1');
    expect(calendar.segments.first.start, at('2026-11-18 08:00'));
    expect(calendar.segments.first.end, at('2026-11-18 09:30'));
    expect(calendar.segments.first.source, SegmentSource.manual);
    expect(calendar.segments[1].tentative, isTrue);

    final settings = calendar.settings;
    expect(settings.timezoneOffsetMinutes, _offset);
    expect(settings.planningStartDate, '2026-11-18');
    expect(settings.planningDays, 14);
    expect(settings.weekly.forWeekday(1).length, 2);
    expect(settings.weekly.forWeekday(2), isEmpty);
    expect(settings.exceptions.single.closed, isTrue);
    expect(settings.exceptions.single.note, '看巡演');
    expect(settings.occupancies.single.title, '线性代数');
    expect(settings.pendingNotes, isNotEmpty);
    expect(settings.timezoneId, kDefaultTimezoneId);
  });

  test('a pre-0.06 version without calendar loads and is not 24/7', () {
    final json = versionWith(const CalendarSchedule()).toJson();
    json.remove('calendar');
    final decoded = PlanVersion.fromJson(json);
    expect(decoded.calendar.segments, isEmpty);
    expect(decoded.calendar.autoGenerated, isFalse);
    expect(decoded.calendar.settings.hasAvailability, isFalse);
    // It must still be saveable: a missing field is filled in on the next write.
    expect(decoded.toJson()['calendar'], isA<Map<String, dynamic>>());
  });

  test('the gantt sub-mode is remembered per conversation', () {
    final conversation = Conversation(
      id: 'conv-1',
      title: 't',
      createdAt: DateTime.utc(2026, 11, 18),
      updatedAt: DateTime.utc(2026, 11, 18),
      chartMode: 'gantt',
      ganttMode: 'calendar',
    );
    final decoded = Conversation.fromJson(conversation.toJson());
    expect(decoded.ganttMode, 'calendar');

    // A conversation written before 0.06 keeps the old relative-hour behaviour.
    final legacy = conversation.toJson()..remove('ganttMode');
    expect(Conversation.fromJson(legacy).ganttMode, 'relative');
  });

  test('segments of removed tasks are dropped on version inheritance', () {
    final inherited = sampleCalendar().inheritedBy({'task-a'});
    expect(inherited.segments.map((s) => s.taskId), ['task-a']);
    expect(inherited.settings.planningStartDate, '2026-11-18',
        reason: 'availability settings belong to the plan, not to a task');
  });

  test('a restart (SessionStore save + load) keeps segments, hours and mode', () async {
    final dir = createTempDataDir('calendar_persist');
    addTearDown(() => dir.deleteSync(recursive: true));
    final store = SessionStore(dir);
    final version = versionWith(sampleCalendar());
    final conversation = Conversation(
      id: 'conv-persist',
      title: '排程',
      createdAt: DateTime.utc(2026, 11, 18),
      updatedAt: DateTime.utc(2026, 11, 18),
      versions: [version],
      currentVersionId: version.id,
      chartMode: 'gantt',
      ganttMode: 'calendar',
    );
    await store.ensureLayout();
    await store.saveConversation(conversation);
    await store.saveIndex([ConversationSummary.of(conversation)]);

    // Fresh store instance == next process start.
    final reopenedStore = SessionStore(dir);
    final loaded = await reopenedStore.loadConversation('conv-persist');
    expect(loaded, isNotNull);
    expect(loaded!.ganttMode, 'calendar');
    final calendar = loaded.currentVersion!.calendar;
    expect(calendar.segments.length, 2);
    expect(calendar.minutesForTask('task-a'), 90);
    expect(calendar.settings.weekly.forWeekday(1).length, 2);
    expect(loaded.currentVersion!.tasks.first.estimatedHours, 1.5);
  });
}

