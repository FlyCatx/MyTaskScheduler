// 冲突详情与建议面板（R1-C）。
//
// 这里只负责“看得懂 + 可确认”的 UI：
//  * 解释每条冲突的类型/日期时刻/区间/来源/涉及任务/剩余需求/可用容量；
//  * 展示由 state/conflict_suggestions.dart 本地确定性生成的建议（调整前后、
//    受影响任务、截止风险、新增冲突数）；
//  * 预览与提交都带版本戳（计划 revision + 时间表 revision + 排程快照签名）；
//    预览期间数据变化时重新计算并让用户重新确认，绝不用过期建议覆盖新数据；
//  * 提交通过调用方传入的 commit 回调（生产环境 = AppController.applyCalendarEdit），
//    因此是一次可撤销的事务；冲突本身仍然“允许带冲突保存”。

