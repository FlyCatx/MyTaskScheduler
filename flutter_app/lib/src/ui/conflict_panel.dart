                  '· ${snapshot.nameOf(taskId)}：'
                  '${_segmentsLabel(snapshot.schedule, taskId, clock)}',
                  key: Key('conflict-preview-before-$taskId'),
                  style: TextStyle(
                    fontSize: 11,
