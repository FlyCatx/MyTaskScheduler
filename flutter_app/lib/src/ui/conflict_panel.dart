  final ConflictSnapshot snapshot;

  const _ConflictPreviewDialog({
    required this.suggestion,
    required this.snapshot,
  });

  @override
  Widget build(BuildContext context) {
    final clock = snapshot.schedule.settings.clock;
    final after = suggestion.scheduleAfter;
    final affected = suggestion.affectedTaskIds.isEmpty
        ? <String>[]
        : suggestion.affectedTaskIds;
