      key: const Key('conflict-preview-dialog'),
      title: Row(
        children: [
          Icon(Icons.visibility_outlined, size: 18, color: TsColors.accent),
          const SizedBox(width: 8),
          Expanded(
            child: Text(
              '建议预览：${suggestion.label}',
              style: const TextStyle(fontSize: 15),
