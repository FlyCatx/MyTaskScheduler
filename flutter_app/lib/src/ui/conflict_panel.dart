                  '· ${snapshot.nameOf(taskId)}：'
                  '${_segmentsLabel(after, taskId, clock)}',
                  key: Key('conflict-preview-after-$taskId'),
                  style: TextStyle(
                    fontSize: 11,
                    height: 1.5,
                    color: TsColors.ready,
                  ),
                ),
              const SizedBox(height: 6),
              for (final change in suggestion.changes)
                Text(
                  change,
                  style: TextStyle(
                    fontSize: 11,
                    height: 1.5,
                    color: TsColors.textSecondary,
                  ),
                ),
              const SizedBox(height: 6),
              Wrap(
                spacing: 14,
                runSpacing: 4,
                children: [
                  Text(
                    '受影响任务：'
                    '${suggestion.affectedTaskIds.map(snapshot.nameOf).join('、')}',
                    style: TextStyle(
                      fontSize: 10.5,
                      color: TsColors.textFaint,
                    ),
                  ),
                  Text(
                    '新增冲突：${suggestion.addedConflictCount} 处',
                    key: const Key('conflict-preview-added'),
                    style: TextStyle(
                      fontSize: 10.5,
                      color: suggestion.addedConflictCount == 0
                          ? TsColors.ready
                          : TsColors.blocked,
                    ),
                  ),
                  Text(
                    '截止风险：${suggestion.deadlineRisk ? '有' : '无'}',
                    key: const Key('conflict-preview-deadline'),
                    style: TextStyle(
                      fontSize: 10.5,
                      color: suggestion.deadlineRisk
                          ? TsColors.blocked
                          : TsColors.textFaint,
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 8),
              Text(
                '应用前会再次核对版本：如果预览期间数据变化，会重新计算并让你重新确认。',
                style: TextStyle(
                  fontSize: 10.5,
                  height: 1.5,
                  color: TsColors.textFaint,
                ),
              ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          key: const Key('conflict-preview-cancel'),
          onPressed: () => Navigator.of(context).pop(false),
          child: const Text('返回'),
        ),
        FilledButton(
          key: const Key('conflict-preview-apply'),
          onPressed: () => Navigator.of(context).pop(true),
          child: const Text('应用此建议'),
        ),
      ],
    );
  }

  static String _segmentsLabel(
    CalendarSchedule? schedule,
    String taskId,
    WallClock clock,
  ) {
    if (schedule == null) return '（未提供新排程）';
    final own = schedule.forTask(taskId);
    if (own.isEmpty) return '（未排期）';
    return own
        .map((s) => instantRangeLabel(clock, s.start, s.end))
        .join('、');
  }
}

