/// 冲突预览/提交使用的版本戳。
///
/// [planRevision] 对应 PlanVersion.revision；[timetableRevision] 对应
/// Timetable.revision（-1 表示没有结构化时间表）；[scheduleSignature] 是
/// CalendarSchedule 内容的确定性签名（同一快照 → 同一签名）。
class ConflictVersionStamp {
  final int planRevision;
  final int timetableRevision;
  final String scheduleSignature;

  const ConflictVersionStamp({
    required this.planRevision,
    required this.timetableRevision,
    required this.scheduleSignature,
  });

  /// 当前屏幕上“正在看的版本”，用于预览与提交。
  String get label => '计划版本 rev $planRevision · '
      '时间表 rev ${timetableRevision < 0 ? '未设置' : timetableRevision}';

  bool matches(ConflictVersionStamp other) =>
      planRevision == other.planRevision &&
      timetableRevision == other.timetableRevision &&
      scheduleSignature == other.scheduleSignature;

  @override
  bool operator ==(Object other) =>
      other is ConflictVersionStamp && matches(other);

  @override
  int get hashCode => Object.hash(
        planRevision,
        timetableRevision,
        scheduleSignature,
      );

  @override
  String toString() => label;
}

/// 日历内容的确定性签名：相等的数据 → 相等的字符串。
/// 签名覆盖设置、每个片段的身份/时间/来源/暂定/本地 revision，以及是否自动生成过。
String calendarScheduleSignature(CalendarSchedule schedule) {
  final segments = <String>[
    for (final s in schedule.segments.toList()
      ..sort((a, b) => a.id.compareTo(b.id)))
      '${s.id}|${s.taskId}|${s.start.millisecondsSinceEpoch}|'
          '${s.end.millisecondsSinceEpoch}|${s.source.name}|${s.tentative}|'
          '${s.revision}',
  ];
  return <String>[
    jsonEncode(schedule.settings.toJson()),
    schedule.autoGenerated ? 'auto' : 'manual',
    segments.join('\n'),
  ].join('\n---\n');
}

/// 打开冲突详情时读取的一份“当前快照”。提交前会再次读取 [currentSnapshot]，
/// 用 [ConflictVersionStamp] 判断数据是否在预览期间变化。
class ConflictSnapshot {
  final CalendarSchedule schedule;
  final List<SchedulingTask> tasks;
  final DateTime now;
  final Map<String, String> taskNames;
  final ConflictVersionStamp stamp;

  const ConflictSnapshot({
    required this.schedule,
    required this.tasks,
    required this.now,
    required this.taskNames,
    required this.stamp,
  });

  String nameOf(String taskId) {
    final name = taskNames[taskId];
    if (name != null && name.trim().isNotEmpty) return name;
    for (final t in tasks) {
      if (t.id == taskId) return t.name;
    }
    return taskId;
  }
}

/// 冲突详情对话框：解释 + 定位 + 建议（预览/提交带版本校验）。
///
/// [onLocate] 是真正的“在甘特图中定位”入口；[onOpenTimetable] 是“修改时间表”
/// 的手动入口（可选，没有时退回定位入口）。两者都只读，不改数据。
Future<void> showConflictDetailsDialog(
  BuildContext context, {
  required ConflictDetail detail,
  required ConflictSnapshot snapshot,
  required ConflictSnapshot Function() currentSnapshot,
  required Future<bool> Function(CalendarEditOutcome outcome) commit,
  bool canEdit = true,
  VoidCallback? onLocate,
  VoidCallback? onOpenTimetable,
}) {
  return showDialog<void>(
    context: context,
    builder: (_) => _ConflictDetailsDialog(
      detail: detail,
      snapshot: snapshot,
      currentSnapshot: currentSnapshot,
      commit: commit,
      canEdit: canEdit,
      onLocate: onLocate,
      onOpenTimetable: onOpenTimetable,
    ),
  );
}

/// 建议预览对话框：调整前后、受影响任务、截止风险、新增冲突与版本说明。
/// 返回 true 表示用户确认“应用此建议”，真正的版本校验与提交由调用方完成。
Future<bool?> showConflictPreviewDialog(
  BuildContext context, {
  required ConflictSuggestion suggestion,
  required ConflictSnapshot snapshot,
}) {
  return showDialog<bool>(
    context: context,
    builder: (_) => _ConflictPreviewDialog(
      suggestion: suggestion,
      snapshot: snapshot,
    ),
  );
}

class _ConflictDetailsDialog extends StatefulWidget {
  final ConflictDetail detail;
  final ConflictSnapshot snapshot;
  final ConflictSnapshot Function() currentSnapshot;
  final Future<bool> Function(CalendarEditOutcome outcome) commit;
  final bool canEdit;
  final VoidCallback? onLocate;
  final VoidCallback? onOpenTimetable;

  const _ConflictDetailsDialog({
    required this.detail,
    required this.snapshot,
    required this.currentSnapshot,
    required this.commit,
    required this.canEdit,
    this.onLocate,
    this.onOpenTimetable,
  });

  @override
  State<_ConflictDetailsDialog> createState() => _ConflictDetailsDialogState();
}

class _ConflictDetailsDialogState extends State<_ConflictDetailsDialog> {
  late ConflictSnapshot _snapshot;
  ConflictDetail? _detail;
  List<ConflictSuggestion> _suggestions = const <ConflictSuggestion>[];
  String? _staleMessage;
  String? _appliedMessage;
  String? _errorMessage;
  bool _busy = false;
  bool _applied = false;

  @override
  void initState() {
    super.initState();
    _snapshot = widget.snapshot;
    _recompute();
  }

  void _recompute() {
    final details = explainConflicts(
      schedule: _snapshot.schedule,
      tasks: _snapshot.tasks,
      now: _snapshot.now,
      taskNames: _snapshot.taskNames,
    );
    ConflictDetail? target;
    for (final candidate in details) {
      if (sameConflict(candidate.conflict, widget.detail.conflict)) {
        target = candidate;
        break;
      }
    }
    target ??= details.isEmpty ? null : details.first;
    _detail = target;
    _suggestions = target == null
        ? const <ConflictSuggestion>[]
        : suggestForConflict(
            detail: target,
            schedule: _snapshot.schedule,
            tasks: _snapshot.tasks,
            now: _snapshot.now,
            taskNames: _snapshot.taskNames,
          );
  }

  Future<void> _preview(ConflictSuggestion suggestion) async {
    final confirmed = await showConflictPreviewDialog(
      context,
      suggestion: suggestion,
      snapshot: _snapshot,
    );
    if (confirmed == true && mounted) {
      await _applySuggestion(suggestion);
    }
  }

  Future<void> _applySuggestion(ConflictSuggestion suggestion) async {
    if (!widget.canEdit || _busy || _applied) return;
    final scheduleAfter = suggestion.scheduleAfter;
    if (scheduleAfter == null) return;

    // 版本校验：预览之后数据变了就重新计算，绝不应用过期建议。
    final current = widget.currentSnapshot();
    if (!current.stamp.matches(_snapshot.stamp)) {
      final previous = _snapshot.stamp.label;
      setState(() {
        _snapshot = current;
        _staleMessage = '日历在预览期间已变化（$previous → ${current.stamp.label}），'
            '已重新计算，请重新确认建议；不会用过期建议覆盖新数据。';
        _errorMessage = null;
        _recompute();
      });
      return;
    }

    setState(() {
      _busy = true;
      _errorMessage = null;
      _staleMessage = null;
    });
    // 危险/过期建议不能误应用：提交前再确认“这条冲突在当前快照里仍存在”。
    final freshDetails = explainConflicts(
      schedule: _snapshot.schedule,
      tasks: _snapshot.tasks,
      now: _snapshot.now,
      taskNames: _snapshot.taskNames,
    );
    final stillExists = freshDetails
        .any((d) => sameConflict(d.conflict, widget.detail.conflict));
    if (!stillExists) {
      setState(() {
        _busy = false;
        _staleMessage = '该冲突已不存在（数据已变化），建议已失效；不会应用过期建议。';
        _recompute();
      });
      return;
    }
    final outcome = CalendarEditOutcome(
      schedule: scheduleAfter,
      label: '应用冲突建议：${suggestion.kind.label}',
      message: '基于 ${_snapshot.stamp.label}；${suggestion.changes.join('；')}',
    );
    final ok = await widget.commit(outcome);
    if (!mounted) return;
    setState(() {
      _busy = false;
      if (ok) {
        _applied = true;
        _appliedMessage =
            '已应用建议（${suggestion.kind.label}），可用“撤销”恢复。';
      } else {
        _errorMessage = '应用失败：排程未改变，请重试或手动调整。';
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    final detail = _detail;
    final clock = _snapshot.schedule.settings.clock;
    return AlertDialog(
      key: const Key('conflict-detail-dialog'),
      title: Row(
        children: [
          Icon(Icons.warning_amber_rounded, size: 18, color: TsColors.blocked),
          const SizedBox(width: 8),
          const Expanded(
            child: Text('冲突解释与建议', style: TextStyle(fontSize: 15)),
          ),
        ],
      ),
      content: SizedBox(
        width: 620,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              if (detail != null)
                ..._detailSection(detail, clock)
              else
                Text(
                  '该冲突已不存在（数据已变化）。',
                  key: const Key('conflict-detail-missing'),
                  style: TextStyle(fontSize: 12, color: TsColors.textSecondary),
                ),
              if (_staleMessage != null)
                _noteBox(
                  key: const Key('conflict-stale-message'),
                  text: _staleMessage!,
                  tone: TsColors.pending,
                ),
              if (_appliedMessage != null)
                _noteBox(
                  key: const Key('conflict-applied-message'),
                  text: _appliedMessage!,
                  tone: TsColors.ready,
                ),
              if (_errorMessage != null)
                _noteBox(
                  key: const Key('conflict-error-message'),
                  text: _errorMessage!,
                  tone: TsColors.blocked,
                ),
              const SizedBox(height: 8),
              if (detail != null && !_applied) _suggestionsSection(detail),
              if (!widget.canEdit)
                _noteBox(
                  key: const Key('conflict-readonly-note'),
                  text: '当前是历史版本/运行中，只能查看解释与建议，不能应用。',
                  tone: TsColors.textSecondary,
                ),
            ],
          ),
        ),
      ),
      actionsPadding: EdgeInsets.zero,
      actions: [
        TsDialogActions(
          actions: [
            if (detail != null && widget.onLocate != null)
              TsDialogAction(
                key: const Key('conflict-detail-locate'),
                label: '在甘特图中定位',
                role: TsDialogActionRole.primary,
                autofocus: true,
                onPressed: () {
                  widget.onLocate!.call();
                  // 只关闭最上层这个对话框，不碰其它路由。
                  Navigator.of(context).pop();
                },
              ),
            TsDialogAction(
              key: const Key('conflict-detail-close'),
              label: '关闭',
              role: TsDialogActionRole.secondary,
              onPressed: () => Navigator.of(context).pop(),
            ),
          ],
        ),
      ],
    );
  }

  /// 绿色区域：只保留一份可读明细（任务/区间/约束/剩余需求/容量/版本）。
  ///
  /// 不再重复一段灰色“解释”：同一事实只写一次；来源作为短标签放在标题行。
  List<Widget> _detailSection(ConflictDetail detail, WallClock clock) {
    final blocking = detail.conflict.kind.isBlocking;
    final remaining = detail.remainingNeedMinutes;
    final names = detail.taskIds.map(_snapshot.nameOf).toList();
    final remainingText = remaining == null
        ? '工时未知（无法计算剩余需求）'
        : '${formatDurationMinutes(remaining)}'
            '（预计 ${formatDurationMinutes(
              _estimateMinutesOf(_snapshot.tasks, detail.conflict.taskId),
            )} − 已安排 '
            '${formatDurationMinutes(
              _snapshot.schedule.minutesForTask(detail.conflict.taskId),
            )}）';
    return <Widget>[
      Wrap(
        spacing: 8,
        runSpacing: 6,
        crossAxisAlignment: WrapCrossAlignment.center,
        children: [
          Text(
            detail.conflict.kind.label,
            key: const Key('conflict-detail-kind'),
            style: TextStyle(
              fontSize: 13,
              fontWeight: FontWeight.w700,
              color: blocking ? TsColors.blocked : TsColors.pending,
            ),
          ),
          Container(
            key: const Key('conflict-detail-source'),
            padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
            decoration: bezierDecoration(
              color: TsColors.pendingSoft,
              radius: 6,
            ),
            child: Text(
              '来源：${detail.sourceLabel}',
              style: TextStyle(fontSize: 11, color: TsColors.pending),
            ),
          ),
        ],
      ),
      const SizedBox(height: 8),
      _detailRow('涉及任务', names.join('、'), key: const Key('conflict-detail-tasks')),
      _detailRow(
        '冲突区间',
        '${instantRangeLabel(clock, detail.start, detail.end)}'
            '（${detail.conflictMinutes} 分钟）',
        key: const Key('conflict-detail-range'),
      ),
      _detailRow(
        '违反的约束',
        detail.conflict.message,
        key: const Key('conflict-detail-message'),
      ),
      _detailRow(
        '剩余需求',
        remainingText,
        key: const Key('conflict-detail-remaining'),
      ),
      _detailRow(
        '同快照可用容量',
        '${formatDurationMinutes(detail.availableCapacityMinutes ?? 0)}'
            '（可用时间表减去全部已排片段）',
        key: const Key('conflict-detail-capacity'),
      ),
      _detailRow(
        '版本',
        '${_snapshot.stamp.label} · 排程签名已记录',
        key: const Key('conflict-detail-version'),
      ),
      const SizedBox(height: 8),
    ];
  }

  /// 黄色区域：只写简短原因或具体动作及影响，不再夹带叙述性说明。
  Widget _suggestionsSection(ConflictDetail detail) {
    final hasAutomatic =
        _suggestions.any((s) => s.kind.appliesSchedule && s.canApply);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Text(
              '调整建议',
              key: const Key('conflict-suggestions-title'),
              style: TextStyle(
                fontSize: 12,
                fontWeight: FontWeight.w600,
                color: TsColors.textPrimary,
              ),
            ),
            const SizedBox(width: 8),
            if (hasAutomatic)
              Text(
                '以下动作可直接应用，应用前会再次核对版本',
                key: const Key('conflict-suggestions-hint'),
                style:
                    TextStyle(fontSize: 10.5, color: TsColors.textFaint),
              ),
          ],
        ),
        const SizedBox(height: 6),
        for (final suggestion in _suggestions) _suggestionCard(suggestion),
      ],
    );
  }

  Widget _suggestionCard(ConflictSuggestion suggestion) {
    final automatic = suggestion.kind.appliesSchedule && suggestion.canApply;
    final tone = suggestion.kind == SuggestionKind.none
        ? TsColors.pending
        : automatic
            ? TsColors.ready
            : TsColors.pending;
    final manual = !automatic &&
        (suggestion.kind == SuggestionKind.none ||
            suggestion.kind == SuggestionKind.openTimetable);
    return Container(
      key: Key('conflict-suggestion-${suggestion.kind.name}'),
      width: double.infinity,
      margin: const EdgeInsets.only(bottom: 6),
      padding: const EdgeInsets.fromLTRB(10, 8, 10, 8),
      decoration: bezierDecoration(
        color: TsColors.surface,
        radius: 8,
        border: Border.all(color: TsColors.border),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Icon(
                _suggestionIcon(suggestion.kind),
                size: 14,
                color: tone,
              ),
              const SizedBox(width: 6),
              Expanded(
                child: Text(
                  suggestion.label,
                  style: TextStyle(
                    fontSize: 12,
                    fontWeight: FontWeight.w600,
                    color: TsColors.textPrimary,
                  ),
                ),
              ),
              if (automatic)
                Text(
                  '新增冲突 ${suggestion.addedConflictCount} 处',
                  key: Key(
                    'conflict-suggestion-${suggestion.kind.name}-added',
                  ),
                  style: TextStyle(fontSize: 10.5, color: tone),
                ),
            ],
          ),
          if (suggestion.unavailableReason != null) ...[
            const SizedBox(height: 4),
            Text(
              suggestion.unavailableReason!,
              key: const Key('conflict-none-reason'),
              style: TextStyle(
                fontSize: 11,
                height: 1.5,
                color: TsColors.pending,
              ),
            ),
          ],
          for (final change in suggestion.changes) ...[
            const SizedBox(height: 3),
            Text(
              change,
              style: TextStyle(
                fontSize: 11,
                height: 1.5,
                color: TsColors.textSecondary,
              ),
            ),
          ],
          if (automatic) ...[
            const SizedBox(height: 4),
            Wrap(
              spacing: 12,
              runSpacing: 2,
              children: [
                Text(
                  '受影响任务：'
                  '${suggestion.affectedTaskIds.map(_snapshot.nameOf).join('、')}',
                  key: Key(
                    'conflict-suggestion-${suggestion.kind.name}-affected',
                  ),
                  style: TextStyle(
                    fontSize: 10.5,
                    color: TsColors.textFaint,
                  ),
                ),
                Text(
                  '截止风险：${suggestion.deadlineRisk ? '有（调整后仍会越过截止）' : '无'}',
                  key: Key(
                    'conflict-suggestion-${suggestion.kind.name}-deadline',
                  ),
                  style: TextStyle(
                    fontSize: 10.5,
                    color: suggestion.deadlineRisk
                        ? TsColors.blocked
                        : TsColors.textFaint,
                  ),
                ),
              ],
            ),
          ],
          if (automatic && widget.canEdit) ...[
            const SizedBox(height: 6),
            Row(
              children: [
                TextButton(
                  key: Key(
                    'conflict-suggestion-preview-${suggestion.kind.name}',
                  ),
                  onPressed: _busy ? null : () => _preview(suggestion),
                  child: const Text('预览调整前后'),
                ),
                const SizedBox(width: 6),
                FilledButton(
                  key: Key('conflict-suggestion-apply-${suggestion.kind.name}'),
                  onPressed: _busy ? null : () => _applySuggestion(suggestion),
                  style: TsButtons.filled(
                    radius: 8,
                    minimumSize: const Size(0, 28),
                    padding: const EdgeInsets.symmetric(horizontal: 12),
                    fontSize: 11.5,
                  ),
                  child: const Text('应用建议'),
                ),
              ],
            ),
          ],
          if (manual && widget.canEdit) ...[
            const SizedBox(height: 6),
            if (widget.onOpenTimetable != null)
              OutlinedButton.icon(
                key: Key(
                    'conflict-suggestion-${suggestion.kind.name}-manual-entry'),
                style: TsButtons.outline(radius: 8, height: 28, fontSize: 11.5),
                onPressed: () {
                  widget.onOpenTimetable!.call();
                  Navigator.of(context).pop();
                },
                icon: const Icon(Icons.schedule_outlined, size: 14),
                label: const Text('打开时间表调整'),
              )
            else if (widget.onLocate != null)
              OutlinedButton.icon(
                key: Key(
                    'conflict-suggestion-${suggestion.kind.name}-manual-entry'),
                style: TsButtons.outline(radius: 8, height: 28, fontSize: 11.5),
                onPressed: () {
                  widget.onLocate!.call();
                  Navigator.of(context).pop();
                },
                icon: const Icon(Icons.open_with, size: 14),
                label: const Text('在甘特图中手动调整'),
              ),
          ],
        ],
      ),
    );
  }

  static IconData _suggestionIcon(SuggestionKind kind) => switch (kind) {
        SuggestionKind.moveToNextGap => Icons.open_with,
        SuggestionKind.splitTask => Icons.content_cut,
        SuggestionKind.rescheduleUnlocked => Icons.auto_awesome,
        SuggestionKind.openTimetable => Icons.schedule_outlined,
        SuggestionKind.none => Icons.info_outline,
      };
}

int _estimateMinutesOf(List<SchedulingTask> tasks, String taskId) {
  for (final t in tasks) {
    if (t.id == taskId) return t.estimatedMinutes;
  }
  return 0;
}

class _ConflictPreviewDialog extends StatelessWidget {
